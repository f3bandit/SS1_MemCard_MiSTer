assert len(G) == 64, len(G)
lines = []
for c in range(32, 96):
    rows = G[chr(c)] + ["....."] * (7 - len(G[chr(c)]))
    for r in range(8):
        bits = 0
        if r < 7:
            for x, ch in enumerate(rows[r]):
                if ch == '#':
                    bits |= 1 << (7 - (x + 1))   # one column of space on the left
        lines.append(f"\t\t{(c-32)*8+r}: q = 8'h{bits:02X};")
